"""Writes the latest Hashnode posts to js/posts.js.

The site can't read Hashnode at runtime (the GraphQL API is paywalled and the
RSS feed sends no CORS headers), so a GitHub Action runs this on a schedule.

usage: python3 scripts/sync_posts.py
"""
import json
import math
import re
import urllib.request
import xml.etree.ElementTree as ET
from email.utils import parsedate_to_datetime
from html import unescape
from pathlib import Path

FEED = "https://hitarth.hashnode.dev/rss.xml"
OUT = Path(__file__).resolve().parent.parent / "js" / "posts.js"
LIMIT = 5
WORDS_PER_MINUTE = 200
CONTENT = "{http://purl.org/rss/1.0/modules/content/}encoded"


def read_time(html):
    words = len(re.sub(r"<[^>]+>", " ", unescape(html or "")).split())
    return f"{max(1, math.ceil(words / WORDS_PER_MINUTE))} min read"


def main():
    req = urllib.request.Request(FEED, headers={"User-Agent": "portfolio-sync"})
    root = ET.fromstring(urllib.request.urlopen(req, timeout=30).read())

    posts = []
    for item in root.iter("item"):
        published = parsedate_to_datetime(item.findtext("pubDate"))
        cover = item.find("enclosure")
        posts.append({
            "title": item.findtext("title", "").strip(),
            "excerpt": item.findtext("description", "").strip(),
            "url": item.findtext("link", "").strip(),
            "date": published.strftime("%Y-%m-%d"),
            "readTime": read_time(item.findtext(CONTENT)),
            "tag": item.findtext("category", "").strip(),
            "cover": cover.get("url") if cover is not None else None,
        })
    posts.sort(key=lambda p: p["date"], reverse=True)

    body = json.dumps(posts[:LIMIT], indent=2, ensure_ascii=False)
    OUT.write_text(f"// Generated by scripts/sync_posts.py. Do not edit by hand.\nwindow.HB_POSTS = {body};\n")
    print(f"wrote {len(posts[:LIMIT])} posts to {OUT}")


if __name__ == "__main__":
    main()
